"""Writes src/width_table.agc: the columns of each code point from U+0300 on, as glibc's wcwidth(3) gives
them in a UTF-8 locale, which most terminals follow. A character that is not printable is drawn as U+FFFD, one
column. Run it again on a newer glibc to follow a newer Unicode, then `agentica fmt src/width_table.agc`."""

import ctypes
import ctypes.util
import locale
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "width_table.agc"
FIRST = 0x300
LAST = 0x10FFFF
PER_LINE = 8


def main() -> None:
    locale.setlocale(locale.LC_CTYPE, "C.UTF-8")
    libc = ctypes.CDLL(ctypes.util.find_library("c"))
    starts: list[int] = []
    widths: list[int] = []
    for code in range(FIRST, LAST + 1):
        width = libc.wcwidth(code) if libc.iswprint(code) else 1
        width = 1 if width < 0 else width
        if not widths or widths[-1] != width:
            starts.append(code)
            widths.append(width)
    libc.gnu_get_libc_version.restype = ctypes.c_char_p
    version = libc.gnu_get_libc_version().decode()
    lines = [
        f"## Generated by scripts/width_table.py from glibc {version}; do not edit by hand.",
        "## From STARTS[i] up to the next start, a code point takes WIDTHS[i] columns.",
        "",
        "STARTS = [",
        *rows([f"0x{code:x}" for code in starts]),
        "]",
        "WIDTHS = [",
        *rows([str(width) for width in widths]),
        "]",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"{OUT}: {len(starts)} runs", file=sys.stderr)


def rows(items: list[str]) -> list[str]:
    return ["  " + ", ".join(items[i : i + PER_LINE]) + "," for i in range(0, len(items), PER_LINE)]


if __name__ == "__main__":
    main()
